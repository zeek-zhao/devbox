#!/usr/bin/env bash
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
. "$HERE/../../scripts/lib/common.sh"
cd "$HERE"

NS=db_l1_pg_07_serial_sequence
psql_db "DROP DATABASE IF EXISTS $NS" >/dev/null
psql_db "CREATE DATABASE $NS" >/dev/null

sql_file="$(mktemp)"
trap 'rm -f "$sql_file"' EXIT
cat >"$sql_file" <<SQL
\set QUIET 1
\connect $NS
CREATE TABLE legacy_items (
    id SERIAL PRIMARY KEY,
    label text NOT NULL
);
CREATE TABLE standard_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label text NOT NULL
);
BEGIN;
SELECT nextval(pg_get_serial_sequence('legacy_items', 'id'));
ROLLBACK;
SELECT nextval(pg_get_serial_sequence('legacy_items', 'id'));
INSERT INTO legacy_items (label) VALUES ('legacy') RETURNING id;
SELECT 'currval=' || currval(pg_get_serial_sequence('legacy_items', 'id'));
INSERT INTO standard_items (label) VALUES ('standard') RETURNING id;
SQL
psql_file "$sql_file"
